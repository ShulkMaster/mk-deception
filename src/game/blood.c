void gusher_destroy_list(void) {
    MkPtr* next;
    MkPtr* ptr;

    if (&gusher_list != 0) {
        ptr = gusher_list;
        while (ptr != 0) {
            MkHdr* hdr;

            hdr = ptr->hdr;
            if (ptr->instance != hdr->instance) {
                next = ptr->next;
                ptr->hdr = 0;
                destroy_mkptr(ptr);
                ptr = next;
                continue;
            }

            hdr = blood_as_generic_pdata(hdr);
            if (hdr != 0 && hdr->instance != 0U) {
                BloodProcVtableRef vtbl;

                vtbl.base = (MkVtableMkproc*)hdr->vtbl;
                vtbl.blood->destroy((MkProc*)hdr);
            }
            ptr = ptr->next;
        }
    }
    gusher_list = 0;
}

